输出模式：

支持两种输出模式：

一、实时流式输出

- 实时显示任务阶段
- 实时显示生成进度
- 已生成的用例可以逐步出现
- 适合用户观察生成过程

二、完整输出

- 等待生成和评审全部完成
- 完成后统一展示结果
- 适合批量生成和后台处理

需要让普通用户容易理解两种模式的区别，不要只显示技术术语。

